"""Freeze path-based scope corrections from the archived annual source inventory.

Selection uses paths and provenance, never complexity values or parser outcomes.
"""
import argparse, hashlib, json, tarfile
from pathlib import Path
HERE = Path(__file__).resolve().parent
CASES = {'odoo__odoo':'python', 'jenkinsci__jenkins':'java', 'apache__tomcat':'java'}
def main(sources):
    evidence=[]
    for repo,language in CASES.items():
        scope=json.loads((HERE/'selection'/('odoo-probe-scope.json' if language=='python' else 'probe-scope.json')).read_text())
        scope['name']=repo+'-reviewed-scope-v1'
        scope['exclude_directory_names']=sorted(set(scope['exclude_directory_names']+['_vendor']))
        rules={}
        if language=='python':
            rules.update({'doc/':'Documentation and migration illustrations.', 'setup/':'Packaging tooling.', 'setup.py':'Packaging entry point.', 'bin/pychart/':'Bundled PyChart, copyright Yasushi Saito.', 'openerp/pychart/':'Bundled PyChart after package rename.', 'bin/addons/base/ir/workflow/pydot/':'Bundled pydot package.', 'addons/email_template/html2text.py':'Bundled html2text, author Aaron Swartz.', 'addons/mail/models/html2text.py':'Bundled html2text after move.', 'addons/document_page/web/widgets/rss/feedparser.py':'Bundled feedparser.', 'addons/wiki/web/widgets/rss/feedparser.py':'Bundled feedparser after move.'})
        if repo=='apache__tomcat':
            scope['name']=repo+'-reviewed-scope-v2'
            scope['generated_markers']+=['generated by:jjtree&javacc','generated by:javacc']
            scope['generated_marker_evidence']='Explicit JavaCC-generated parser and support-file headers. JJTree-only node skeleton markers are retained because their implementations may be maintained manually. See results/generated-header-audit.json.'
            rules.update({'webapps/docs/':'Documentation examples.', 'java/org/apache/tomcat/dbcp/':'Repackaged Apache Commons DBCP and Pool; build.xml identifies repackaging.', 'java/org/apache/tomcat/util/http/fileupload/':'Repackaged Commons FileUpload/IO; package-info.java identifies copying.', 'java/org/apache/tomcat/util/bcel/':'Bundled Apache BCEL derivative; separate BCEL component.'})
        for archive in sorted(sources.glob(repo+'-*.tar')):
            with tarfile.open(archive) as tar:
                for m in tar.getmembers():
                    if not m.isfile() or not m.name.endswith('.py'):continue
                    parts=m.name.split('/')
                    # Odoo framework test add-ons (not business modules such as account_test).
                    for i,part in enumerate(parts[:-1]):
                        if part.startswith('test_') and i and parts[i-1]=='addons':
                            prefix='/'.join(parts[:i+1])+'/'
                            rules[prefix]='Framework test add-on; path starts test_ directly under addons.'
                    if parts[-1]=='test_models.py':rules[m.name]='Test fixture models, excluded independently of their metric values.'
                    if m.name in rules or m.name.endswith(('pychart/__init__.py','pydot/pydot.py')):
                        data=tar.extractfile(m).read()
                        evidence.append({'archive':archive.name,'path':m.name,'sha256':hashlib.sha256(data).hexdigest(),'header':data[:1500].decode('utf8','replace')})
        scope['exclude_prefixes']=sorted(set(scope['exclude_prefixes'])|set(rules))
        scope.setdefault('exclusion_evidence',{}).update(rules)
        (HERE/'protocols'/f'{repo}.json').write_text(json.dumps(scope,indent=2)+'\n')
    (HERE/'results/scope-review-evidence.json').write_text(json.dumps(evidence,indent=2)+'\n')
if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--sources',type=Path,required=True)
    main(ap.parse_args().sources)
